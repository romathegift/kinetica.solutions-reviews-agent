"""
Telegram-слой HITL-гейта.

Раскладка
---------
    card.py      — ЧИСТЫЕ функции: текст карточки, клавиатура, callback_data,
                   маркер правки. Ни одного сетевого вызова — поэтому
                   тестируется без бота, без токена и без базы.
    sender.py    — отправка карточки оператору.
    handlers.py  — обработка нажатий и присланной правки; зовёт reviews_agent.hitl.

HTTP-слоя здесь НЕТ: приложение вебхука живёт в reviews_agent/api/service.py.
Причина — оно со временем понесёт не только вебхук Telegram (health, приём
отзывов с площадки, служебные ручки), и держать его внутри telegram-пакета
станет неверно.

Направление зависимостей
------------------------
    api.service -> tg.handlers -> {tg.card, hitl}
    scripts.run_graph -> {hitl, tg.sender}

reviews_agent.hitl НЕ знает про Telegram. Это позволяет прогонять граф
из CLI, когда бот недоступен, и держит оркестрацию пригодной для любого
будущего фронтенда решения.

ПОЧЕМУ ПАКЕТ НАЗЫВАЕТСЯ tg, А НЕ telegram
-----------------------------------------
python-telegram-bot импортируется как `telegram`. Локальный пакет с тем же
именем затеняет библиотеку в любой конфигурации, где reviews_agent/ попадает
на sys.path напрямую (запуск скрипта из этой папки, часть инструментов,
некоторые сборки Docker). Тогда `from telegram import Bot` резолвится
в этот пакет и падает ImportError'ом в месте, никак не связанном с причиной.
Общее правило: локальный пакет не называется именем внешней зависимости.
"""