"""
Гардрейлы: детерминированная пост-проверка черновика.

ФЛАГИ, А НЕ БЛОКИРОВКА. Ни одна проверка здесь не отменяет отправку черновика
в Telegram — черновик уходит оператору всегда, флаги едут вместе с ним строками
на карточке. Причина в цене ошибки: проверки приблизительны (счёт предложений
по пунктуации, эмодзи по категории Unicode), и блокировка на приблизительной
проверке отняла бы у оператора нормальный ответ, ничего не дав взамен. Оператор
и так читает каждый черновик; задача флага — направить его взгляд, а не решить
за него.

ОТСЮДА ЖЕ ПРИОРИТЕТ ТОЧНОСТИ НАД ПОЛНОТОЙ. Пропущенный флаг стоит оператору
пары секунд чтения. Ложный флаг стоит доверия ко ВСЕМ флагам сразу: после
третьего ложного срабатывания их перестают читать, и система флагов умирает
целиком. Поэтому везде, где выбор между «поймать лишнее» и «не соврать»,
выбрано второе. Первый прогон на фикстурах поймал два ложных флага
(«повернемось» и эмодзи на нейтральном вопросе) — оба закрыты, см. brand.py
и правило эмодзи ниже.

ПОЧЕМУ КОД, А НЕ ВТОРОЙ ВЫЗОВ МОДЕЛИ. Всё, что здесь проверяется, —
арифметика и сравнение строк. LLM-судья дал бы недетерминизм, задержку и счёт
за проверку правил, которые считаются точно. Ровно тот же принцип, что
в compute_escalation: модель решает семантику, код решает арифметику.

ГРАНИЦЫ ПРОВЕРОК — названы, а не спрятаны:
  * счёт предложений идёт по терминальной пунктуации: «т.д.», экзотическая
    вёрстка или эмодзи вместо точки («передамо бариста 🙂 Чекаємо на вас»)
    собьют счёт на единицу вниз;
  * эмодзи считаются по категории Unicode So: ZWJ-последовательность («👨‍👩‍👧»)
    посчитается как три, а «™» и «→» посчитаются как эмодзи;
  * язык ловит утечку в английский ответ и подмену целиком, но украинскую
    подпись в английском тексте не поймает: 19 кириллических букв на ~150 дают
    долю 0.11, и ни один порог не отличит их от утечки слова, не запретив
    заодно легитимную латиницу в украинском ответе. Подпись ловит проверка
    подписи — это две разные работы, и подменять одну другой нельзя.

ДОЛГ (назван, не исправлен): cyrillic_ratio импортируется из nodes/ingest.py —
это чистая функция, но лежит она в слое узлов, а гардрейлы живут слоем ниже.
Правильное место — отдельный модуль языка в корне пакета. Не двигаю: ingest
закрыт, а заводить ВТОРОЙ детектор языка нельзя категорически — Ingest сказал
бы «uk», гардрейл «en», и мы бы получили ложные флаги на ровном месте.
"""

import re
import unicodedata

from reviews_agent.brand import ACTION_PHRASES, CLICHES, SIGNATURES
from reviews_agent.nodes.ingest import cyrillic_ratio
from reviews_agent.state import Category, Language, Sentiment

# --- Коды флагов -------------------------------------------------------------
#
# Машинные коды, а не готовые украинские строки. Причина: состояние графа —
# ядро системы, а украинский текст карточки — забота слоя tg/. Положив сюда
# «Мова відповіді не збігається», мы бы связали ядро с языком интерфейса
# оператора: английский оператор, второй канал (email, веб) или перевод карточки
# потребовали бы правки состояния и чекпоинтов. Код -> текст маппится в tg/.

TRUNCATED = "TRUNCATED"
CONTEXT_INCOMPLETE = "CONTEXT_INCOMPLETE"
EMPTY_DRAFT = "EMPTY_DRAFT"
LANG_MISMATCH = "LANG_MISMATCH"
LENGTH_OUT_OF_RANGE = "LENGTH_OUT_OF_RANGE"
SIGNATURE_MISSING = "SIGNATURE_MISSING"
CLICHE = "CLICHE"
EMOJI_FORBIDDEN = "EMOJI_FORBIDDEN"
EMOJI_TOO_MANY = "EMOJI_TOO_MANY"
PII_IN_REPLY = "PII_IN_REPLY"
PROMISE_REQUIRES_ACTION = "PROMISE_REQUIRES_ACTION"

# Полный список кодов в порядке выдачи.
# Нужен слою tg/: по нему проверяется, что у каждого кода есть человеческий
# текст. Иначе новый флаг доехал бы до оператора голым кодом.
ALL_FLAGS = (
    TRUNCATED,
    CONTEXT_INCOMPLETE,
    EMPTY_DRAFT,
    LANG_MISMATCH,
    LENGTH_OUT_OF_RANGE,
    SIGNATURE_MISSING,
    CLICHE,
    EMOJI_FORBIDDEN,
    EMOJI_TOO_MANY,
    PII_IN_REPLY,
    PROMISE_REQUIRES_ACTION,
)

# --- Пороги ------------------------------------------------------------------

# Языковые полосы для ЧЕРНОВИКА — не порог 0.5 из Ingest, и это принципиально.
#
# У Ingest задача другая: вход может быть каким угодно, и порог лишь делит два
# языка (замер: uk = 1.0, en = 0.0, спам с латинским хендлом = 0.88). Черновик
# же обязан быть ОДНОЯЗЫЧНЫМ по построению — значит проверять надо не «какой
# это язык», а «не протекло ли сюда чужое».
#
# ПОЛОСЫ АСИММЕТРИЧНЫ, потому что асимметричны сами языки в этом проекте.
#
# uk: латиница в украинском ответе ЛЕГИТИМНА — «Wi-Fi» приходит прямо из
#     kb_005, и запрещать её нельзя. Порог 0.85 держится за счёт подписи:
#     «Команда «Медовий Ранок»» добавляет 19 кириллических букв в КАЖДЫЙ
#     украинский ответ. Замер на худшем случае — короткий ответ с латинским
#     термином: «Так, Wi-Fi безкоштовний. Команда «Медовий Ранок»» = 34 из 38
#     букв, доля 0.895, запас есть.
#
# en: кириллица в английском ответе НЕЛЕГИТИМНА ВСЕГДА, поэтому 0.0, а не
#     «немного можно». Имя бренда пишется латиницей по прямому правилу kb_025
#     («The Medovyi Ranok team, spelled exactly this way»), названия блюд
#     обязаны переводиться. Сценария, где кириллическая буква в английском
#     ответе уместна, не существует.
#
# ЭТО НЕ ПЕДАНТИЗМ, А СЛЕДСТВИЕ УСТРОЙСТВА БАЗЫ. Факты (faq/policy) хранятся
# только на украинском: английские дубли удалены намеренно — дубль занимал два
# слота top-k под один факт, а реранкер язык запроса не предпочитает (замер
# на rev_006: украинский kb_001 встал ВЫШЕ английского дубля). Значит
# английский ответ ВСЕГДА строится переводом украинского факта, и утечка
# исходного слова — штатный риск, а не экзотика.
# Прежнее значение 0.15 этот риск не ловило: на ответе в ~150 букв оно
# разрешало до 22 кириллических — целую фразу «Сирники, гранола та
# авокадо-тост» (28 букв, доля 0.157, ровно на грани).
CYRILLIC_MIN_UK = 0.85
CYRILLIC_MAX_EN = 0.0

# Длина ответа из бренд-бука: kb_015 «від одного до чотирьох речень»,
# kb_016 «between one and four sentences».
MIN_SENTENCES = 1
MAX_SENTENCES = 4

# Сколько цифр должно быть в кандидате, чтобы считать его телефоном или картой.
# Ниже — это уже не контакт: короткие числа в ответе легитимны («понад
# 15 хвилин» из kb_009).
MIN_PII_DIGITS = 9

# --- Регулярные выражения ----------------------------------------------------

# Конец предложения: терминальная пунктуация, за которой пробел или конец строки.
#
# Требование пробела после — не украшение, а защита от дробных чисел:
# без него «1.5 л» распалось бы на два предложения. Многоточие U+2026 включено
# явно, иначе оно не считалось бы концом вовсе.
SENTENCE_END_RE = re.compile(r"[.!?…]+(?:\s|$)")

EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")

# Кандидат в телефон/карту: цифра, затем длинный прогон из цифр, пробелов,
# скобок и дефисов, затем цифра.
#
# Двоеточие в класс НЕ входит намеренно — на нём разбивается «8:00-21:00»
# из kb_001, самый частый факт в базе. Точка тоже не входит: «15.03.2026»
# не телефон.
PHONE_RE = re.compile(r"\+?\d[\d\s()\-]{7,}\d")

# Кавычки, которые снимаются при нормализации.
#
# Апострофов ' и ’ здесь НЕТ намеренно: в украинском это буква по функции
# («здоров'я», «обов'язково»), и снятие разорвало бы слова пополам.
QUOTE_CHARS = "«»„“”\"‹›"


def normalize(text: str) -> str:
    """
    Приводит текст к виду, в котором сравнение строк осмысленно.

    Casefold вместо lower: он корректен для регистра за пределами ASCII.

    Кавычки снимаются, потому что типографика — шум, а не смысл. Модель может
    написать подпись в «ялинках», в "прямых" или вовсе без кавычек — это одна
    и та же подпись, и флаг за неё был бы ложным. А вот другие СЛОВА в подписи —
    уже сигнал, и он остаётся.

    Применяется к ОБЕИМ сторонам сравнения: и к черновику, и к канону из
    brand.py. Поэтому константы там пишутся в естественном виде.
    """
    text = text.casefold()
    for char in QUOTE_CHARS:
        # Заменяем на пробел, а не на пустоту: иначе «слово«друге» слиплось бы
        # в одно слово. Лишние пробелы схлопнет следующая строка.
        text = text.replace(char, " ")
    return re.sub(r"\s+", " ", text).strip()


def count_sentences(text: str) -> int:
    """
    Считает предложения по терминальной пунктуации.

    Ответ без точки в конце («Дякуємо») — одно предложение, а не ноль:
    пустые фрагменты после разбиения отбрасываются.
    """
    return len([part for part in SENTENCE_END_RE.split(text) if part.strip()])


def count_emoji(text: str) -> int:
    """
    Считает эмодзи по категории Unicode So (Symbol, other).

    Только So. Категория Sk (Symbol, modifier) не берётся, хотя в ней лежат
    модификаторы тона кожи: там же живут «^» и «`», и обычная кавычка-циркумфлекс
    дала бы ложный флаг. Ловить редкий эмодзи ценой ложных срабатываний —
    ровно тот размен, который здесь запрещён.
    """
    return sum(1 for char in text if unicodedata.category(char) == "So")


def emoji_limit(category: Category, sentiment: Sentiment) -> int:
    """
    Сколько эмодзи разрешено бренд-буком в этом ответе.

    kb_017 (uk) и kb_024 (en): «максимум один на відповідь і тільки
    в позитивному контексті. У відповідях на скарги емодзі не використовуємо».

    ЧТО ТАКОЕ «ПОЗИТИВНЫЙ КОНТЕКСТ» — ТРАКТОВКА, И ОНА ПРОВЕРЕНА ПРОГОНОМ.
    Формулировка клиента допускает два чтения:

      строгое  — контекст позитивен только при sentiment == positive;
      по смыслу — контекст позитивен везде, кроме разбора проблемы.

    Строгое чтение было в коде первым и провалилось на rev_005: ответ на
    дружелюбный вопрос про собаку («принесемо і миску з водою... чекаємо на
    вас 🐾») получил EMOJI_FORBIDDEN. Ни один бренд-менеджер этот ответ не
    завернёт — значит флаг ловил не нарушение, а собственную трактовку.

    Решает вторая фраза правила: она называет область запрета — ЖАЛОБЫ.
    Нейтральный вопрос, отвеченный тепло, — позитивный контекст.

    Условие по sentiment оставлено рядом с category не для симметрии:
    негативный отзыв, не попавший в complaint (например, разочарованный
    вопрос), — тоже не место для эмодзи.

    Двусмысленность формулировки реальна и уходит в чек-лист онбординга:
    правило переписывается словами клиента, а не додумывается нами.
    """
    if category == "complaint" or sentiment == "negative":
        return 0
    return 1


def strip_signature(normalized_draft: str, language: Language) -> tuple[str, bool]:
    """
    Отрезает подпись с конца черновика.

    Возвращает (тело без подписи, подпись на месте).

    ЗАЧЕМ ОТРЕЗАТЬ ПЕРЕД СЧЁТОМ ДЛИНЫ: подпись — это предложение по пунктуации,
    но не предложение по смыслу. Канонический пример kb_019 состоит из трёх
    фраз плюс подпись; посчитав подпись, мы бы получили 4 и упёрлись в потолок
    на ОБРАЗЦЕ, который бренд сам считает эталонным. Любой нормальный ответ
    из четырёх фраз тогда давал бы ложный флаг.

    Хвостовая пунктуация снимается до сравнения: «Команда «Медовий Ранок».» —
    та же подпись, точка в конце не делает её другой.
    """
    signature = normalize(SIGNATURES[language])
    tail = normalized_draft.rstrip(" .!?…")

    if tail.endswith(signature):
        return tail[: -len(signature)], True
    return normalized_draft, False


def check_language(draft: str, language: Language) -> bool:
    """
    Проверяет, что в черновике нет утечки чужого языка.

    Полосы асимметричны и не взаимозаменяемы: латиница в украинском ответе
    законна, кириллица в английском — нет. См. CYRILLIC_MIN_UK / CYRILLIC_MAX_EN.
    """
    ratio = cyrillic_ratio(draft)
    if language == "uk":
        return ratio >= CYRILLIC_MIN_UK
    return ratio <= CYRILLIC_MAX_EN


def has_pii(text: str) -> bool:
    """
    Ищет контактные данные, которые нельзя повторять в публичном ответе.

    Гость может написать телефон или email в отзыве — модель способна повторить
    их в ответе, а ответ публикуется под отзывом на весь интернет. Утечка тут
    не наша ошибка ввода, а наша ошибка вывода, и цена у неё внешняя.

    Телефон подтверждается ДВАЖДЫ: сначала форма (regex), затем количество цифр.
    Одной формы мало — она поймала бы «0 800» с четырьмя цифрами. Номера карт
    (13–19 цифр) ловятся тем же условием и отдельного правила не требуют.
    """
    if EMAIL_RE.search(text):
        return True

    for match in PHONE_RE.finditer(text):
        if sum(char.isdigit() for char in match.group()) >= MIN_PII_DIGITS:
            return True
    return False


def check_draft(
    draft: str,
    language: Language,
    category: Category,
    sentiment: Sentiment,
    truncated: bool = False,
    context_incomplete: bool = False,
) -> list[str]:
    """
    Собирает все флаги по одному черновику. Единственная точка входа.

    Два флага приходят ПАРАМЕТРАМИ, а не выводятся из текста:
      truncated          — обрыв по max_tokens, это факт из ответа API;
      context_incomplete — в контексте не хватало голоса бренда или примера
                           нужной пары (категория, язык), это факт из Generate.
    Логически они могли бы жить в узле, но тогда флаги собирались бы в двух
    местах, и их порядок зависел бы от порядка строк в вызывающем коде.
    Список один, порядок стабильный, тесты воспроизводимы.

    Порядок флагов = порядок ALL_FLAGS.
    """
    flags: list[str] = []

    if truncated:
        flags.append(TRUNCATED)
    if context_incomplete:
        flags.append(CONTEXT_INCOMPLETE)

    if not draft.strip():
        # Дальше идти незачем: на пустой строке сработают ещё и «нет подписи»,
        # и «длина вне диапазона» — три флага вместо одной настоящей причины.
        # Шум утопил бы диагноз.
        flags.append(EMPTY_DRAFT)
        return flags

    if not check_language(draft, language):
        flags.append(LANG_MISMATCH)

    normalized = normalize(draft)
    body, has_signature = strip_signature(normalized, language)

    # Ноль предложений здесь означает, что в черновике нет ничего, кроме
    # подписи — тела нет, и диапазон это ловит.
    if not MIN_SENTENCES <= count_sentences(body) <= MAX_SENTENCES:
        flags.append(LENGTH_OUT_OF_RANGE)

    if not has_signature:
        flags.append(SIGNATURE_MISSING)

    if any(normalize(phrase) in normalized for phrase in CLICHES[language]):
        flags.append(CLICHE)

    # Лимит эмодзи считает отдельная функция: правило бренда двусмысленно,
    # и его трактовка заслуживает собственного места с обоснованием,
    # а не строки в общем списке проверок. См. emoji_limit().
    allowed = emoji_limit(category, sentiment)
    if count_emoji(draft) > allowed:
        flags.append(EMOJI_FORBIDDEN if allowed == 0 else EMOJI_TOO_MANY)

    if has_pii(draft):
        flags.append(PII_IN_REPLY)

    # Обещание, требующее ручного действия. Проверяется ТЕКСТ ЧЕРНОВИКА,
    # а не входные факты: так ловятся и обещания, которых в policy не было.
    #
    # Это не ошибка — kb_009 прямо велит обещать промокод. Флаг лишь превращает
    # молчаливое обещание в строку «потрібна дія» на карточке: пайплайн пишет
    # текст, промокоды не отправляет, и после публикации кто-то обязан это
    # сделать руками.
    if any(normalize(phrase) in normalized for phrase in ACTION_PHRASES[language]):
        flags.append(PROMISE_REQUIRES_ACTION)

    return flags