"""
Cross-encoder реранкер (BAAI/bge-reranker-base) — вторая ступень поиска.

ЗАЧЕМ ОН НУЖЕН. Эмбеддинг кодирует отзыв и чанк ПОРОЗНЬ и меряет угол между
векторами — то есть отвечает на вопрос "похожи ли эти два текста", а не
"решает ли этот регламент проблему гостя". Для двух украинских текстов про
проблему с заказом ответ всегда "похожи", и скоры слипаются.

Замер на фикстурах (шаг 6):
    e5:  rev_003 -> kb_009 (НУЖНЫЙ) = 0.8368
         rev_004 -> kb_013 (ШУМ)    = 0.8408  <- шум ВЫШЕ нужного
    Порога, который пропускает 0.8368 и режет 0.8408, не существует.

    bge: rev_003 -> kb_009 (НУЖНЫЙ) = -2.139
         rev_004 -> kb_013 (ШУМ)    = -2.970  <- шум НИЖЕ нужного
    Порядок перевёрнут, окно порога появилось.

Cross-encoder получает пару (запрос, документ) ВМЕСТЕ и обучен на бинарной
задаче "релевантно / нет" — поэтому и различает то, что вектор не различает.

Выбор модели (проверено по fastembed 0.8.0, июль 2026):
    jina-reranker-v2-base-multilingual — CC-BY-NC, некоммерческая, отпадает
    ms-marco-MiniLM L-6/L-12           — только английский
    jina-reranker-v1 tiny-en/turbo-en  — только английский
    BAAI/bge-reranker-base             — MIT, XLM-RoBERTa, работает на украинском
"""

from functools import lru_cache

from fastembed.rerank.cross_encoder import TextCrossEncoder

from reviews_agent.embeddings import CACHE_DIR

MODEL_NAME = "BAAI/bge-reranker-base"

# АСИММЕТРИЧНЫЕ ПОРОГИ. Цена ошибки у категорий разная, поэтому и пороги разные.
#
# complaint (-2.25): лишний чанк дорого стоит. Агент пообещает гостю с двойным
#   списанием переделать напиток — не то, что нужно. Порог строгий: пропускает
#   kb_009 на rev_003 (-2.139) и режет kb_013 на rev_004 (-2.970).
#   Пустой результат тут не сбой, а сигнал: решения в базе нет -> эскалация.
#
# question (-8.0): потерять факт дорого, лишний факт — бесплатно. Гость спросил
#   про молоко, а в ответе упомянуты ещё и часы завтраков — не проблема.
#   Порог мягкий: пропускает все нужные (худший kb_007 на rev_006 = -7.407)
#   и режет явный мусор (kb_005 Wi-Fi = -10.193).
#
# ВАЖНО: числа выведены на 4 фикстурах и годятся для демо. На реальном клиенте
# они пересчитываются на его истории отзывов через scripts/calibrate_threshold.py.
RERANK_THRESHOLDS = {
    "complaint": -2.25,
    "question": -8.0,
}


@lru_cache
def get_reranker() -> TextCrossEncoder:
    """
    Singleton реранкера.

    Модель ~1.04 ГБ, инициализация — загрузка ONNX-весов в память.
    Кэш общий с эмбеддингами (~/.cache/fastembed).
    """
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    return TextCrossEncoder(model_name=MODEL_NAME, cache_dir=str(CACHE_DIR))


def rerank_scores(query: str, documents: list[str]) -> list[float]:
    """
    Считает логиты релевантности для пар (запрос, документ).

    Возвращает список в ТОМ ЖЕ порядке, что и documents — не отсортированный.
    Сортировка и отсечение по порогу — забота вызывающего кода: так проще
    сопоставить скор с исходным чанком.

    Шкала: логиты, не вероятности. Обычный диапазон -11..0, выше — релевантнее.
    Отрицательные значения нормальны и не означают "нерелевантно".
    """
    if not documents:
        # Пустой вход: реранкер на пустом списке может повести себя по-разному
        # в зависимости от версии, поэтому решаем сами.
        return []

    # .rerank() отдаёт генератор — разворачиваем в список
    return [float(score) for score in get_reranker().rerank(query, documents)]


def threshold_for(category: str) -> float:
    """
    Порог для категории.

    KeyError вместо дефолта намеренно: единственные категории, доходящие
    до реранкера, — complaint и question (praise и spam минуют Retrieve
    по маршруту роутера). Если сюда пришло что-то ещё — это баг графа,
    и он должен быть громким.
    """
    return RERANK_THRESHOLDS[category]