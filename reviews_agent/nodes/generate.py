"""
Узел Generate: черновик публичного ответа через Claude Sonnet 5.

ТРИ ИСТОЧНИКА КОНТЕКСТА, И ОНИ РАЗНОЙ ПРИРОДЫ:

  ФАКТЫ (context_chunks) — приходят из Retrieve, найдены поиском под конкретный
      отзыв. Динамика: у каждого отзыва свои.
  ГОЛОС БРЕНДА (voice) и ПРИМЕРЫ (example) — берутся здесь прямой выборкой
      по type. Статика: конфигурация клиента, одна и та же для всех отзывов.

Почему статику не ищет Retrieve: поиск ранжирует по релевантности запросу,
а правила тона релевантны ВСЕГДА. Пропустив их через реранкер, мы бы позволили
порогу выбросить правило подписи из ответа на подяку — и получили бы отзыв
без подписи по причине «низкий скор». Плюс слоты top_k конечны, и правила
конкурировали бы с фактами за место.

Отсюда же следует, что ветка praise минует Retrieve, но контекст бренда
получает: подяке факты не нужны, а правила тона нужны.

ЧТО ВОЗВРАЩАЕТ В СОСТОЯНИЕ: brand_context (ради трассировки — по чекпоинту
видно, на чём именно построен ответ), draft и guardrail_flags.

ИСКЛЮЧЕНИЯ НАРУЖУ НЕ ЛОВИМ: обработка ошибок (retry с backoff, error_handler
на add_node, алерт админу) навешивается на уровне графа на шаге 9. Узел обязан
честно упасть, иначе механизм не сработает.

ДОЛГ (назван, не исправлен): get_client импортируется из nodes/classify.py.
Это третий импорт между узлами-соседями в проекте (retrieve->classify,
guardrails->ingest, generate->classify), и правило трёх сработало: место
для клиента Anthropic — отдельный reviews_agent/llm.py, а для детекта языка —
reviews_agent/language.py. Переезд делается ОТДЕЛЬНЫМ шагом после того, как
Generate заработает: смешивать рефакторинг закрытых узлов с новой фичей —
верный способ не понять, что именно сломалось.
Дублировать get_client здесь нельзя: два lru_cache дали бы два HTTP-клиента
и два пула соединений вместо одного.
"""

from psycopg.rows import dict_row

from reviews_agent.brand import BRAND_NAME
from reviews_agent.db import get_connection
from reviews_agent.guardrails import check_draft
from reviews_agent.nodes.classify import get_client
from reviews_agent.prompts.generate import (
    EMPTY_FACTS_BLOCK,
    FACTS_BLOCK_TEMPLATE,
    NO_FACTS_BLOCK,
    REPLY_OPEN_TAG,
    STOP_SEQUENCE,
    SYSTEM_PROMPT_TEMPLATE,
    USER_PROMPT_TEMPLATE,
)
from reviews_agent.state import KnowledgeChunk, ReviewState

# Sonnet 5, а не Haiku: классификация — это выбор из четырёх меток, а здесь
# текст уходит в публикацию от имени бренда. Цена ошибки внешняя, и экономить
# на модели в единственном месте пайплайна, которое видит клиент, бессмысленно.
MODEL = "claude-sonnet-5"

# МЫШЛЕНИЕ ВЫКЛЮЧЕНО ЯВНО.
#
# На Sonnet 5 adaptive thinking включён ПО УМОЛЧАНИЮ: запрос без поля thinking
# уходит с мышлением, и на дефолтном effort=high модель думает почти всегда.
# Это смена дефолта — на Sonnet 4.6 тот же запрос уходил БЕЗ мышления.
#
# Для нашей задачи мышление неверно по трём причинам:
#
#   1. max_tokens — жёсткий лимит на СУММУ (мышление + текст). С включённым
#      мышлением stop_reason="max_tokens" перестаёт означать «ответ обрезан»
#      и начинает означать «бюджет кончился, на чём — неизвестно». Гардрейл
#      TRUNCATED построен ровно на этом различении и начал бы врать оператору:
#      документация прямо описывает сценарий «почти всё мышление, затем
#      обрезанный ответ».
#   2. Задача — не многошаговое рассуждение, а короткий текст по явным
#      правилам. Sonnet 5 следует инструкциям буквально, а правила в промпте
#      названы поимённо.
#   3. Мышление billable на КАЖДОМ отзыве. На пайплайне, где отзывов тысячи,
#      это разница между рабочей юнит-экономикой и нерабочей.
#
# Значение задано ЯВНО, а не опущено: дефолт уже менялся между релизами модели,
# и полагаться на него — значит отдать поведение прода чужому расписанию.
#
# ЭТО ОТКРЫТЫЙ ВОПРОС, А НЕ ЗАКРЫТЫЙ. Включить adaptive на низком effort
# и сравнить соблюдение правил — замер через scripts/preview_generate.py,
# а не спор. Если включим, max_tokens поднимается вместе с этим, а TRUNCATED
# придётся переосмыслить.
THINKING = {"type": "disabled"}

# Ответ по бренд-буку — от одного до четырёх предложений. С новым токенизатором
# Sonnet 5 (примерно +30% токенов на тот же текст; кириллица и так дороже
# латиницы) это ~250-400 токенов. Запас взят намеренно: max_tokens здесь
# не ограничитель длины, а ДЕТЕКТОР АНОМАЛИИ. Длину держит промпт, а гардрейл
# LENGTH_OUT_OF_RANGE ловит промахи. Упёрлись в 1000 — значит модель ушла
# в разнос, и флаг TRUNCATED об этом скажет. Поставь мы 400 — обрыв стал бы
# рутиной, и флаг потерял бы смысл.
#
# Лимит на ЧИСТЫЙ ТЕКСТ, потому что мышление выключено. Включат мышление —
# это число обязано вырасти, иначе бюджет съест рассуждение.
MAX_TOKENS = 1000

# TEMPERATURE ЗДЕСЬ НЕТ — И ЭТО НЕ УПУЩЕНИЕ.
#
# Sonnet 5 отвергает temperature, top_p и top_k с любым НЕдефолтным значением
# (400 invalid_request_error), независимо от того, включено мышление или нет.
# Параметр убирается целиком: temperature=0 упал бы так же, как 0.7.
#
# На задачу это не влияет — и вскрывает ошибку в моём же обосновании. 0.7
# ставилось ради РАЗНООБРАЗИЯ: под соседними похожими отзывами («довго чекав
# каву», «чекав 20 хвилин») бренд не должен публиковать ответы-близнецы, это
# читается как бот. Но дефолт API — temperature=1.0, то есть 0.7 разнообразие
# УМЕНЬШАЛ относительно дефолта. Параметр не служил причине, которой был
# объяснён. Убрав его, получаем ровно то, чего добивались, — и меньшим числом
# строк.
#
# На детерминизм проверок это по-прежнему не влияет: язык, подпись, длина
# и эмодзи считаются кодом по факту готового текста, а не предсказываются
# заранее.

# Категории, для которых пишется ответ. spam сюда не доходит: роутер уводит
# его в spam_filter (review_status=skipped) и дальше в END.
GENERATED_CATEGORIES = frozenset({"complaint", "question", "praise"})

# Куда падать, если контекста на языке отзыва в базе клиента не оказалось.
# Ось фолбэка — ЯЗЫК, и только он.
#
# Взять пример чужой КАТЕГОРИИ нельзя категорически: бодрое «Дякуємо за теплі
# слова!» под жалобой — катастрофа, и поймать её нечем, тон не проверяется
# кодом. А промах по языку ловится гардрейлом LANG_MISMATCH детерминированно.
# Поэтому жертвуем языком примера, никогда — категорией.
OTHER_LANGUAGE = {"uk": "en", "en": "uk"}


def render_chunks(chunks: list[KnowledgeChunk]) -> str:
    """
    Превращает чанки в строки для промпта.

    Тип и язык в скобках — не украшение. Retrieve язык НЕ фильтрует намеренно
    (e5 многоязычная, украинский факт находится по английскому запросу),
    поэтому в контексте английского ответа штатно окажется «(faq, uk)».
    Системный промпт велит переводить содержимое таких чанков — но чтобы
    правило сработало, модель должна ВИДЕТЬ, что перед ней чужой язык.

    Скоры (vector_score, rerank_score) в промпт не идут сознательно: это
    внутренние числа поиска. Модель не умеет их интерпретировать, зато вполне
    способна взвесить факты по логитам реранкера или упомянуть их в ответе
    гостю.
    """
    return "\n".join(
        f"- ({chunk['type']}, {chunk['language']}) {chunk['content']}"
        for chunk in chunks
    )


def fetch_static_context(
    client_id: str, language: str, category: str
) -> tuple[list[KnowledgeChunk], list[KnowledgeChunk], bool]:
    """
    Достаёт голос бренда и примеры ответов. Возвращает (voice, examples, неполон).

    ОДИН ЗАПРОС НА ОБА ЯЗЫКА, выбор языка — в Python. Причина: статики
    у клиента десяток чанков, и тянуть их разом дешевле, чем ходить в базу
    второй раз ради фолбэка. Заодно вся логика выбора становится чистой
    и проверяемой без базы.

    voice по category НЕ фильтруется: правила тона категориям не принадлежат.
    kb_014 («реакція на негатив») лежит с category=NULL и работает на каждой
    жалобе именно через статику. Что voice не обзаведётся категорией по ошибке
    оператора — забота scripts/validate_kb.py на онбординге, а не рантайма.

    Третий элемент кортежа — флаг неполноты контекста. Он уходит в
    guardrail_flags и дальше на карточку оператору: сработавший фолбэк обязан
    быть виден. На базе «Медового Ранку» (voice 4/4, example 3/3) он не
    срабатывает ни разу — это предохранитель на случай неполной базы клиента,
    которую мы дописывать не вправе.
    """
    with get_connection() as conn:
        with conn.cursor(row_factory=dict_row) as cur:
            rows = cur.execute(
                """
                SELECT content, type, language, source
                FROM knowledge_base
                WHERE client_id = %s
                  AND (type = 'voice' OR (type = 'example' AND category = %s))
                ORDER BY id
                """,
                (client_id, category),
            ).fetchall()

    def pick(chunk_type: str, lang: str) -> list[KnowledgeChunk]:
        return [
            KnowledgeChunk(
                content=row["content"],
                type=row["type"],
                language=row["language"],
                source=row["source"],
                # Статика не ранжируется — скоров у неё нет и быть не может.
                # Придумать ей единицу значило бы соврать в отладке.
                vector_score=None,
                rerank_score=None,
            )
            for row in rows
            if row["type"] == chunk_type and row["language"] == lang
        ]

    incomplete = False

    voice = pick("voice", language)
    if not voice:
        voice = pick("voice", OTHER_LANGUAGE[language])
        incomplete = True

    examples = pick("example", language)
    if not examples:
        examples = pick("example", OTHER_LANGUAGE[language])
        incomplete = True

    return voice, examples, incomplete


def generate(state: ReviewState) -> ReviewState:
    """
    Узел графа: черновик ответа плюс детерминированная пост-проверка.

    Черновик уходит оператору ВСЕГДА, с флагами или без. Гардрейлы не
    блокируют — см. reviews_agent/guardrails.py.
    """
    category = state["category"]
    if category not in GENERATED_CATEGORIES:
        # Ответ на спам от имени бренда — публичный конфуз. Если сюда пришёл
        # спам, сломан роутер, и молчать об этом нельзя.
        raise ValueError(f"Generate не пишет ответ для категории {category!r}")

    language = state["language"]
    sentiment = state["sentiment"]

    voice, examples, context_incomplete = fetch_static_context(
        client_id=state["client_id"],
        language=language,
        category=category,
    )

    # Три состояния фактов — и это ТРИ РАЗНЫХ сообщения модели, а не два.
    #
    #   praise            -> Retrieve не запускался, искать было нечего.
    #                        Блока фактов нет вовсе.
    #   факты найдены     -> обычный режим.
    #   Retrieve пуст     -> искали и не нашли. Это режим rev_004 (двойное
    #                        списание, policy в базе нет намеренно).
    #
    # Разница между первым и третьим принципиальна. Пустой <facts></facts>
    # модель прочитает как «фактов не дали» и восполнит их сама — то есть
    # выдумает компенсацию, которую бренд пообещает публично и не выполнит.
    # Поэтому пустота названа вслух и превращена в инструкцию (NO_FACTS_BLOCK).
    #
    # На category, а не на отсутствие ключа: ветка praise минует Retrieve
    # по топологии графа, и это инвариант дизайна. Опора на .get() -> None
    # сломалась бы от одной строки в инициализации состояния.
    facts = state.get("context_chunks") or []
    if category == "praise":
        facts_block = EMPTY_FACTS_BLOCK
    elif facts:
        facts_block = FACTS_BLOCK_TEMPLATE.format(facts=render_chunks(facts))
    else:
        facts_block = NO_FACTS_BLOCK

    response = get_client().messages.create(
        model=MODEL,
        max_tokens=MAX_TOKENS,
        # Мышление выключено явно — см. THINKING. Без этого поля Sonnet 5
        # уходит с adaptive thinking, и max_tokens перестаёт быть бюджетом
        # текста.
        thinking=THINKING,
        system=SYSTEM_PROMPT_TEMPLATE.format(brand_name=BRAND_NAME),
        # Модель остановится на </reply>, и сам тег в ответ не попадёт.
        stop_sequences=[STOP_SEQUENCE],
        # Диалог обязан заканчиваться сообщением пользователя: Sonnet 5
        # отвергает префилл ассистента с 400. Открывающий тег теперь просит
        # промпт, а срезает — код ниже.
        messages=[
            {
                "role": "user",
                # .format() не рекурсивен: фигурные скобки, попавшие внутрь
                # текста отзыва или чанков, вторично не интерпретируются
                # и KeyError не вызовут.
                "content": USER_PROMPT_TEMPLATE.format(
                    language=language,
                    category=category,
                    sentiment=sentiment,
                    brand_rules=render_chunks(voice),
                    examples=render_chunks(examples),
                    facts_block=facts_block,
                    text=state["text"],
                ),
            },
        ],
    )

    # Блоки ответа фильтруем ПО ТИПУ, а не берём нулевой.
    #
    # response.content[0].text развалился бы с AttributeError, окажись первым
    # блок мышления: поля text у него нет вовсе. Сейчас мышление выключено
    # и текстовый блок один — но цена страховки нулевая, а цена её отсутствия —
    # падение узла ровно в тот день, когда мышление решат включить. Причём
    # молча не обойдётся: на Sonnet 5 блоки мышления приходят в ответе даже
    # при display="omitted", просто с пустым полем.
    #
    # "".join по пустому генератору даёт "" — отдельная проверка на пустой
    # content не нужна, а флаг EMPTY_DRAFT поставят гардрейлы.
    raw = "".join(block.text for block in response.content if block.type == "text")

    # Срезаем всё до открывающего тега включительно.
    #
    # Префилла больше нет, поэтому тег пишет сама модель — а рядом с ним может
    # написать и преамбулу («Here is the reply:»), которую префилл делал
    # невозможной. partition() закрывает оба случая одним движением:
    #   тег найден -> берём хвост за ним, преамбула отрезана механически;
    #   тега нет   -> берём текст целиком, потому что ответ без тега остаётся
    #                 ответом, и выбросить его было бы хуже, чем показать
    #                 оператору как есть — он всё равно читает каждый черновик.
    #
    # Закрывающий тег в хвост не попадает: на нём модель останавливает
    # стоп-последовательность.
    _, tag_found, tail = raw.partition(REPLY_OPEN_TAG)
    draft = (tail if tag_found else raw).strip()

    flags = check_draft(
        draft=draft,
        language=language,
        category=category,
        sentiment=sentiment,
        # Факт из ответа API, а не догадка по тексту: stop_reason различает
        # «модель закончила» и «кончились токены». Ровно ради этого различения
        # и заведена стоп-последовательность — обрезанный ответ по одному
        # тексту неотличим от законченного.
        truncated=response.stop_reason == "max_tokens",
        context_incomplete=context_incomplete,
    )

    return {
        "brand_context": voice + examples,
        "draft": draft,
        "guardrail_flags": flags,
    }