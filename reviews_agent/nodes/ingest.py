"""
Узел Ingest & detect: нормализация входа и определение языка отзыва.

Язык определяем по алфавиту, без внешней библиотеки: украинский и английский
живут в разных алфавитах, поэтому доля кириллицы разделяет их однозначно.
langdetect или fasttext здесь были бы лишней зависимостью с вероятностной
моделью там, где хватает детерминированного подсчёта — и с риском ошибиться
на коротком тексте, которым отзыв обычно и является.
"""

import unicodedata

from reviews_agent.state import ReviewState

# Порог доли кириллицы среди букв.
# Замер на фикстурах: uk — 1.0, en — 0.0, спам с латинским хендлом — 0.88.
# Запас с обеих сторон огромный, поэтому 0.5 безопасен.
# Порог 0.9 сломал бы спам-фикстуру — она определилась бы как английская.
CYRILLIC_THRESHOLD = 0.5


def cyrillic_ratio(text: str) -> float:
    """
    Доля кириллических букв среди всех букв текста.

    Считаем через unicodedata, а не диапазоном 'а' <= c <= 'я':
    украинские і, ї, є, ґ лежат ВНЕ этого диапазона, и наивная проверка
    занижала бы долю именно на украинском тексте — на самом частом языке
    в нашей базе.

    Цифры, пунктуация, эмодзи и пробелы не считаются: они одинаковы в любом
    языке и только размывают долю. Спам-фикстура с двумя парами эмодзи
    и суммой в долларах — ровно этот случай.
    """
    letters = [c for c in text if c.isalpha()]
    if not letters:
        # Отзыв без букв: только рейтинг, эмодзи или цифры.
        # Возвращаем 0.0 -> язык определится как en.
        # Для демо на 7 фикстурах это недостижимо, но в реальной интеграции
        # с Google Maps отзыв без текста — обычное дело, и падать тут нельзя.
        return 0.0

    cyrillic = sum(1 for c in letters if "CYRILLIC" in unicodedata.name(c, ""))
    return cyrillic / len(letters)


def ingest(state: ReviewState) -> ReviewState:
    """
    Первый узел графа: нормализует текст и ставит язык.

    Возвращает ТОЛЬКО свои поля — LangGraph домержит их в состояние.
    Возвращать весь словарь целиком не нужно и вредно: так труднее понять,
    какой узел за какое поле отвечает.
    """
    text = state["text"].strip()
    ratio = cyrillic_ratio(text)

    return {
        "text": text,
        "language": "uk" if ratio >= CYRILLIC_THRESHOLD else "en",
        # Кладём в состояние для отладки и карточки: если детект однажды
        # ошибётся, по этому числу сразу видно, насколько близко к порогу
        # был текст — гадать не придётся.
        "cyrillic_ratio": round(ratio, 4),
    }