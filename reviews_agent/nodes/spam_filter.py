"""
Узел-терминатор ветки spam.

Роутер направляет спам сюда, а не в END напрямую, по одной причине:
чекпоинт должен нести след КАЖДОГО отзыва. Обрыв в END не оставил бы
в состоянии ничего — по базе чекпоинтов нельзя было бы отличить
"спам, осознанно пропущен" от "граф упал до генерации".

Узел ничего не вызывает и не пишет наружу: ни Sonnet, ни карточки
оператору. Только проставляет review_status="skipped" — финальный
статус спам-ветки, симметричный approved/rejected/edited других веток.

Ответ на спам от имени бренда — публичный конфуз. Поэтому спам НЕ должен
дойти до Generate: generate() на нём осознанно падает с ValueError.
Эта топология (spam -> spam_filter -> END) и есть страховка от такого
ответа на уровне графа, а не на уровне надежды.
"""

from reviews_agent.state import ReviewState


def spam_filter(state: ReviewState) -> ReviewState:
    """
    Закрывает обработку спама без генерации ответа.

    Возвращает только своё поле — review_status. LangGraph смержит его
    в состояние, остальные поля остаются как есть.
    """
    return {"review_status": "skipped"}